/**
 * Writes convex/lib/imageCodecs/wasm.ts: the WebAssembly the email copy of a
 * big report is made with (convex/emailCopy.ts), as base64 in a module.
 *
 * Three files, all from Squoosh by way of jSquash: mozjpeg's decoder and
 * encoder (@jsquash/jpeg) and a Lanczos resampler (@jsquash/resize). They
 * are embedded rather than read from node_modules at run time because a
 * Convex function is a bundle: nothing beside the JavaScript is deployed, and
 * a package left out of the bundle for the server to install
 * (`node.externalPackages`) is one more thing that can differ between a
 * laptop, the tests and the cloud. Bytes in a module load the same way in all
 * three.
 *
 * Run it after upgrading either package:
 *
 *   node scripts/embed-image-codecs.mjs
 *
 * `convex/lib/imageCodecs/codecs.test.ts` fails until it has been, because it
 * compares each embedded file's sha256 with the installed one: the glue code
 * that drives a module comes from the package, and a module from another
 * version would be driven with the wrong calls.
 */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(join(root, 'package.json'))

/** Export name → the file in node_modules it is made from. */
export const CODECS = {
  MOZJPEG_DECODER: '@jsquash/jpeg/codec/dec/mozjpeg_dec.wasm',
  MOZJPEG_ENCODER: '@jsquash/jpeg/codec/enc/mozjpeg_enc.wasm',
  LANCZOS_RESIZER: '@jsquash/resize/lib/resize/pkg/squoosh_resize_bg.wasm',
}

function versionOf(specifier) {
  const name = specifier.split('/').slice(0, 2).join('/')
  return JSON.parse(
    readFileSync(require.resolve(`${name}/package.json`), 'utf8'),
  ).version
}

function embedded(specifier) {
  const bytes = readFileSync(require.resolve(specifier))
  return {
    source: `${specifier}@${versionOf(specifier)}`,
    sha256: createHash('sha256').update(bytes).digest('hex'),
    bytes: bytes.length,
    base64: bytes.toString('base64'),
  }
}

const target = join(root, 'convex/lib/imageCodecs/wasm.ts')
const entries = Object.entries(CODECS).map(([name, specifier]) => {
  const file = embedded(specifier)
  return `export const ${name}: EmbeddedWasm = {
  source: '${file.source}',
  sha256: '${file.sha256}',
  bytes: ${file.bytes},
  base64:
    '${file.base64}',
}`
})

writeFileSync(
  target,
  `'use node'

/**
 * GENERATED by scripts/embed-image-codecs.mjs — do not edit. Run that script
 * after upgrading @jsquash/jpeg or @jsquash/resize.
 *
 * The WebAssembly the email copy of a big report is made with, as base64,
 * so it is part of the bundle Convex deploys (see the script for why).
 * \`'use node'\`, so it is bundled for the Node runtime only, the one place
 * it is used.
 */

export type EmbeddedWasm = {
  /** The file it was made from, and that package's version. */
  source: string
  sha256: string
  bytes: number
  base64: string
}

${entries.join('\n\n')}
`,
)

console.log(`wrote ${relative(root, target)}`)
